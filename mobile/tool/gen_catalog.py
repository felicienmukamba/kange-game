def assign(cat, title):
    n = norm(title).replace("’", "'")
    if n in O:
        return O[n]
    for pat, eng, cfg in R:
        if re.search(pat, n):
            return eng, dict(cfg)
    if cat in CAT_DEFAULT:
        eng, cfg = CAT_DEFAULT[cat]
        return eng, dict(cfg)
    return "performance", {}


