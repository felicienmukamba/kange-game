src, out = sys.argv[1], sys.argv[2]
lines = [l.strip() for l in open(src, encoding="utf8") if l.strip()]
lines = [l.replace("&amp;", "&") for l in lines]


def norm(s):
    s = unicodedata.normalize("NFD", s.lower())
    return "".join(c for c in s if unicodedata.category(c) != "Mn")


cat_re = re.compile(r"^(\S+)\s+(\d+)\.\s+(.*)$")
categories, items = [], []
for l in lines[1:]:
    m = cat_re.match(l)
    if m:
        emoji, num, name = m.groups()
        name = re.sub(r"^CHALLENGES\s+", "", name).strip().strip("“”\"")
        name = re.sub(r"\s*\(.*?\)\s*$", "", name) if num != "97" else "Bonus final"
        categories.append({"id": int(num), "emoji": emoji, "name": name.capitalize() if name.isupper() else name})
        continue
    items.append((categories[-1]["id"], re.sub(r"\s+", " ", l.replace("“", "").replace("”", "").replace("\"", "")).strip()))

